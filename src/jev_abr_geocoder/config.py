"""Jev に渡す文言と、判断に使う閾値。

**このファイル以外に、Jev に渡す文字列リテラルと比較用の定数を置かない。**

TypeSafe のドキュメントが「人間がレビューすべきは質問と閾値だけ」と述べている
とおり、これらが散らばるとレビュー不能になる。挙動を知りたい人はここだけ読めば
よい状態を保つ。
"""

from __future__ import annotations

from dataclasses import dataclass

__all__ = [
    "GeocoderConfig",
    "NONE_OPTION",
    "NONE_OPTION_DESCRIPTION",
    "TOWN_QUESTION",
    "BEAM_QUESTION",
    "NUMBER_QUESTION",
]


# --------------------------------------------------------------------- 閾値


@dataclass(frozen=True)
class GeocoderConfig:
    """閾値と挙動の設定。

    **閾値をどう選んだか**（geolonia の難例 7,191 件、Jev 実測、2026-09-26）:

    ==========  ============  ==============
    町字の閾値    カバレッジ      銀ラベル一致
    ==========  ============  ==============
    0.00        99.9%         99.61%
    0.30        99.9%         **99.62%**
    0.50        99.9%         99.61%
    0.60        99.8%         99.55%
    0.70        99.8%         99.54%
    0.95        99.6%         99.46%
    ==========  ============  ==============

    0.30 を採る。0.60 以上でははっきり落ち、0.50 以下はほぼ横ばい。
    0.00 / 0.30 / 0.50 の差は 0.01 ポイント（実数で 1 件未満）で誤差の範囲
    だが、**実際に中身を確認した取りこぼし**が 0.30 で拾える側にある:

    - 京都市中京区一之船入町 (0.41) — 「河原町二条下ル」は通り名で、答えは正しい
    - 江戸川区西小松川町 (0.40) — 同じく正しい

    これらは 0.50 だと捨てられていた。ゲート自体は残しておきたいので 0.00 は
    採らない。

    ただし **この測定だけで決め切れてはいない**。7,191 件のうち Jev に届くのは
    0.4% 程度で、閾値が効く母集団が小さい。docs/eval.md の Tier 1'
    （法人番号公表データ、約 490 万件）を回して確かめる必要がある。
    """

    # --- 判断の閾値 ------------------------------------------------------
    #: 町字を確定したと見なす Jev の confidence 下限
    town_confidence: float = 0.30
    #: 番号を確定したと見なす Jev の confidence 下限。
    #: **未検証** — 上の測定は町字までの索引で行ったため、番号経路が
    #: 母集団に含まれていない。町字に合わせて仮に 0.30 とする。
    number_confidence: float = 0.30
    #: 「候補の中に正解がある」と見なす下限。NONE_OPTION 以外の確率の合計がこれを
    #: 下回ったら、候補を棄却して 1 段粗い粒度で返す
    present_threshold: float = 0.50

    # --- 候補生成 --------------------------------------------------------
    #: Jev の Choice が受け付けるオプション数の上限（API の制約）。
    #: 「該当なし」の予約オプションもこの数に含まれる。
    max_options: int = 255

    # --- 挙動 ------------------------------------------------------------
    #: True にするとファストパスを無効化し、常に Jev を通す（評価用）
    always_rerank: bool = False
    #: 1 リクエストにまとめる入力件数
    batch_size: int = 64
    #: 候補が max_candidates を超えたとき、Jev で分割絞り込み (beam) を行う。
    #: False にすると従来どおり粒度を落とす。
    beam: bool = True
    #: beam に持ち込む町字数の上限。メモリの歯止めでしかない。
    #:
    #: **コストを決めるのは町字数ではなく大字数**で、beam は大字にまとめて
    #: から訊くため。輪島市は町字 8,022 でも大字は 230 で 1 問に収まる。
    #: 最大の福井市でも町字 15,399 / 大字 629。
    beam_max_candidates: int = 20_000
    #: 1 リクエストに載せる入力トークンの目安。
    #:
    #: **Jev の上限は 64k tokens/リクエスト**。実測で 254 件の選択肢 1 分割が
    #: 9,727 トークン（1 選択肢 38.3、日本語は 1 文字あたり約 2.3）なので、
    #: 64k には 6 分割しか入らない。超えると max_tokens_exceeded で
    #: リクエストごと失敗するので、見積もりに余裕を持たせて詰める。
    beam_token_budget: int = 48_000
    #: 1 つの beam リクエストに載せる入力の数。
    #:
    #: トークンに余裕があっても、**複数の入力を 1 リクエストに詰めると
    #: 絞り込みの精度が落ちる**ことが実測で出た（単体なら確信度 0.78〜0.89 で
    #: 解ける入力が、64 件のバッチでは「絞り込めなかった」になる）。
    #: beam に回るのは全体の 0.4% 程度なので、1 入力 1 リクエストにしても
    #: リクエスト数は十数件しか増えない。
    beam_max_asks_per_request: int = 1
    #: 使用するモデル
    model: str = "jev-latest"
    #: Jev の呼び出しタイムアウト（秒）
    timeout: float = 30.0

    @property
    def max_candidates(self) -> int:
        """候補として渡せる件数。

        Choice の選択肢には ``NONE_OPTION`` が 1 つ加わるので、候補はその分
        少なくしないと API の 255 件制限を超える。
        """
        return self.max_options - 1

    def __post_init__(self) -> None:
        if not 2 <= self.max_options <= 255:
            raise ValueError("max_options は 2..255 の範囲（Jev Choice の制約）")
        if self.batch_size < 1:
            raise ValueError("batch_size は 1 以上")


# --------------------------------------------------------------- 該当なし

#: 「候補のどれでもない」を表す予約オプション ID。
#:
#: 別に Noul を立てて「候補に正解が含まれるか」を訊くのではなく、Choice の
#: 選択肢として持たせる。同じ確率分布の中で「該当なし」の確率が出るので
#: 解釈が一貫し、リクエストも 1 問で済む。
NONE_OPTION = "__none__"

NONE_OPTION_DESCRIPTION = (
    "候補のいずれでもない。"
    "正しい住所がこの一覧に無い場合、または入力がそもそも住所ではない場合はこれを選ぶ。"
)

# ----------------------------------------------------------------- 質問文

#: 町字の確定。層1 のトライが出した候補から 1 つ選ばせる。
TOWN_QUESTION = (
    "`対象` の住所が指している町字はどれか。"
    "候補は日本のアドレス・ベース・レジストリに実在する住所である。"
    "入力には誤字・旧字体・漢数字と算用数字の混在・都道府県や郡の省略・"
    "建物名の混入があり得る。表記の一致ではなく、"
    "入力が指そうとしている実在の住所として最も妥当なものを選ぶこと。"
    "町字より後ろの番地・建物名は判断材料にしてよいが、選ぶのは町字である。"
)

#: 候補の絞り込み（beam）の 1 段目。町字が 255 件を超える市区町村で、
#: **先に大字（町名）だけを選ばせて**候補を一桁以上絞る。
#:
#: 町字は「大字 + 丁目 + 小字」なので、大字だけなら選択肢が激減する
#: （福井市 15,399 町字 -> 629 大字、福島市 8,132 -> 205）。丁目や小字は
#: 大字が決まってから 2 段目で選ぶ。
BEAM_QUESTION = (
    "`対象` の住所が指している大字（町名）はどれか。"
    "丁目・小字・番地は見ずに、町名の部分だけで判断すること。"
    "入力には誤字・旧字体・漢数字と算用数字の混在があり得るので、"
    "表記の一致ではなく、入力が指そうとしている町名として最も妥当なものを選ぶ。"
    "対応するものが無いときは「該当なし」を選ぶこと。"
)

#: 番号の確定。町字が決まったあと、残りの数値列を実在レコードに割り当てる。
NUMBER_QUESTION = (
    "`対象` の住所の、`町字` より後ろの部分はどの番号を指しているか。"
    "候補は `町字` に実在する番号である。"
    "入力の数値列には、住所ではない部分（建物名・部屋番号・階数）が"
    "続いていることがある。たとえば「1-2-3 〇〇ハイツ301」の 301 は部屋番号で"
    "あって住所の一部ではない。どこまでが住所かを判断したうえで選ぶこと。"
)
